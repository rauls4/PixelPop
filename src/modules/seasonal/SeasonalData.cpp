// ---------------------------------------------------------------- lookups
// The months of one region out of a season string, as a bit mask (bit 0 = January).
static uint16_t seasonMask(const char *spec, int region) {
  // find the field of this region
  for (int r = 0; r < region && *spec; ) {
    if (*spec++ == '|') r++;
  }
  uint16_t mask = 0;
  while (*spec && *spec != '|') {
    if (*spec == ',') { spec++; continue; }
    char *end;
    long a = strtol(spec, &end, 10);
    if (end == spec) break;
    long b = a;
    spec = end;
    if (*spec == '-') { b = strtol(spec + 1, &end, 10); spec = end; }
    if (a < 1 || a > 12 || b < 1 || b > 12) continue;
    for (int m = (int)a; ; m = m % 12 + 1) {           // a..b, over New Year when b < a
      mask |= (uint16_t)(1u << (m - 1));
      if (m == b) break;
    }
  }
  return mask;
}

bool produceInSeason(const Produce &p, int region, int month) {
  if (month < 1 || month > 12) return false;
  if (region == RG_SOUTHERN) {                           // the Mediterranean, six months apart
    region = RG_MEDITERRANEAN;
    month = (month + 5) % 12 + 1;
  }
  if (region < 0 || region >= RG_SOUTHERN) return false;
  return (seasonMask(p.season, region) >> (month - 1)) & 1;
}

// A rough map: where a place on the globe fits best.
int regionForLocation(float lat, float lon) {
  if (lat < -10.0f) return RG_SOUTHERN;
  const bool americas = lon < -50.0f && lon > -170.0f;
  if (americas && lat >= 24.0f) {
    if (lon <= -117.0f && lat >= 42.0f) return RG_PACIFICNW;
    if (lon <= -114.0f && lat < 42.0f) return RG_CALIFORNIA;
    if (lon <= -109.0f && lat <= 37.0f) return RG_CALIFORNIA;           // Arizona and New Mexico
    if (lon <= -102.0f && lat >= 37.0f) return RG_MOUNTAIN;
    if (lon <= -91.0f && lat < 37.0f)   return RG_SOUTHCENTRAL;
    if (lat < 36.5f) return RG_SOUTHEAST;
    if (lon > -80.5f) return RG_NORTHEAST;
    return RG_MIDWEST;
  }
  if (americas) return RG_SOUTHCENTRAL;                                   // Mexico and south
  if (lat >= 46.0f) return RG_UK;
  return RG_MEDITERRANEAN;                                                // everything warmer, in Europe, Africa or Asia
}
